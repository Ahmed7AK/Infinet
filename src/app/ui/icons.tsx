export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, color, scale = 2 }: { name: IconName; color: string; scale?: number }) {
  const rows = ICONS[name] ?? ICONS.wifi;
  const rects: JSX.Element[] = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < 12; x++) if (r[x] === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} />);
  });
  const px = 12 * scale;
  return (
    <svg width={px} height={px} viewBox="0 0 12 12" fill={color} shapeRendering="crispEdges" aria-hidden>
      {rects}
    </svg>
  );
}
